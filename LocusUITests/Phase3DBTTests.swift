import XCTest

/// Phase 3: crisis skills, check the facts, opposite action, chain
/// analysis, diary card.
final class Phase3DBTTests: SkillsUITestCase {

    func testCalmDownIsTwoTapsAndTIPPBreathingLowersIntensity() {
        launch()
        tap("Toolkit")
        tap("I need to calm down")
        expectText("How intense is it right now?")
        tap("Intensity: 9 out of 10")
        next()
        // At 8+, TIPP is suggested and preselected.
        expectText("TIPP usually works fastest")
        next()
        tap("Paced breathing")
        expectText("Breathe out longer than you breathe in")
        tap("Start")
        expectText("Breathe", timeout: 3)
        tap("Done")
        tap("I'm done")
        tap("Intensity now: 4 out of 10")
        tap("Finish")
        expectText("You got through it")
        expectText("Intensity")
    }

    func testStillHighAfterSTOPOffersAnotherSkillAndSafetyPlan() {
        launch()
        tap("Toolkit")
        tap("I need to calm down")
        tap("Intensity: 9 out of 10")
        next()
        tap("STOP")
        next()
        expectText("Stop.")
        next()
        expectText("Take a step back.")
        next()
        expectText("Observe.")
        tap("Skip")
        expectText("Proceed mindfully.")
        type("Put the phone down and walk outside", into: "What I'll do…")
        next()
        tap("Intensity now: 9 out of 10")
        tap("Finish")
        expectText("Still very intense")
        XCTAssertTrue(button("Try another skill").exists)
        XCTAssertTrue(button("Your safety plan").exists)
        expectText("988")
        tap("Try another skill")
        expectText("Which would help most right now?")
    }

    func testCrisisFromTriageOffersTheMatchedToolAfterwards() {
        launch()
        openToolkit()
        tap("Work through something")
        tap("Help me choose")
        tap("Intensity: 8 out of 10")
        next()
        tap("A loop I keep going around")
        next()
        tap("Start Crisis Skills")
        tap("Intensity: 8 out of 10")
        next()
        next()
        tap("Temperature")
        expectText("heart condition")
        tap("Done")
        tap("I'm done")
        tap("Intensity now: 4 out of 10")
        tap("Finish")
        tap("Continue with Defusion")
        expectText("Defusion")
    }

    func testCheckTheFactsDoesntFitCarriesEmotionIntoOppositeAction() {
        launch()
        startFromToolkit(method: "DBT", tool: "Check the Facts")
        tap("Fear / Anxiety")
        tap("nervous")
        next()
        type("My friend didn't reply to my message for a day.", into: "What happened was…")
        next()
        type("She's angry with me.", into: "I'm assuming…")
        next()
        type("She'll end the friendship", into: "The threat I'm expecting is… (or “none”)")
        slide("How likely is it, really?", to: 0.1)
        next()
        type("She's upset for a while.", into: "The worst realistic outcome…")
        next()
        expectText("Fear fits when")
        tap("Doesn't fit")
        next()
        expectText("doesn't quite fit")
        next()
        slide("Nervous now", to: 0.3)
        tap("Finish")
        expectText("You checked the facts")
        tap("Try Opposite Action")
        expectText("What does nervous urge you to do?")
        type("Keep checking my phone", into: "It makes me want to…")
        next()
        // Fit was already checked, so straight to the action.
        expectText("What's the opposite of that urge")
        tap("Approach what you're avoiding")
        next()
        expectText("Do it all the way.")
        next()
        tap("Now")
        tap("Start now")
        tap("I'm back")
        tap("Yes")
        slide("Nervous now", to: 0.2)
        tap("Finish")
        expectText("You acted against the urge")
    }

    func testOppositeActionWhenEmotionFitsRoutesToProblemSolving() {
        launch()
        startFromToolkit(method: "DBT", tool: "Opposite Action")
        tap("Anger")
        tap("frustrated")
        type("Send an angry email", into: "It makes me want to…")
        next()
        tap("Fits")
        expectText("Solving the problem it's pointing at")
        next()
        type("Ask my manager for a clear deadline", into: "One thing I could do…")
        next()
        slide("Frustrated now", to: 0.4)
        tap("Finish")
        expectText("You made a plan")
    }

    func testChainAnalysisBuildsChainAndSavesIfThenPlan() {
        launch()
        startFromToolkit(method: "DBT", tool: "Chain Analysis")
        type("I snapped at my partner at dinner", into: "I…")
        next()
        type("They asked if I'd paid the bill", into: "It started when…")
        next()
        tap("Poor sleep")
        tap("Stress")
        next()
        tap("Thought")
        type("I'm useless at this", into: "What happened next?")
        tap("Add link")
        tap("Urge")
        type("Shut the conversation down", into: "What happened next?")
        tap("Add link")
        XCTAssertTrue(app.buttons["Move up"].firstMatch.exists)
        next()
        type("They stopped asking", into: "Right after…")
        type("We didn't talk all evening", into: "Later on…")
        next()
        tap("Thought")
        type("Say I need five minutes", into: "Or in your own words…")
        next()
        expectText("Make an if-then plan for next time?")
        next()
        tap("Skip")
        expectText("You mapped the chain")
        expectText("If-then plan saved to Practice")
        expectText("Poor sleep")
    }

    func testDiaryCardSavesAndShowsDoneToday() {
        launch()
        openToolkit()
        tap("Diary card")
        expectText("A quick check-in on today.")
        tap("Sadness")
        tap("lonely")
        tap("Avoid")
        tap("STOP")
        dismissKeyboard()
        tap("Save")
        expectText("Done today")
    }
}
